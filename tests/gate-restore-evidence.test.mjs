import test from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';

// البوابة 4 (الاستعادة) — العيب الذي أوجب هذا الملف:
//
// الفحص 5 في scripts/gate.mjs يستعيد أحدث نسخة احتياطية ويتحقق من سلامتها وسلسلة تدقيقها، وهو فحص سليم.
// لكنه حين لا يجد نسخةً إطلاقًا كان يعيد { ok:true, skipped:true } ونصّه يقول بنفسه «لم يُجرَّب شيء،
// وهذا ليس نجاحًا» — فالنصّ صادق والقيمة تناقضه: البوابة تُصدر أخضر على نظامٍ بلا شبكة أمان.
// وهذا يخالف قاعدة مكتوبة في برومبت المالك: «skipped ليس نجاحًا».
//
// وليست الحالة فرضية. قياس 29 سبتمبر 2026 على الالتزام 63ff911: آخر اختبار استعادة ناجح مسجَّل على
// الترحيل 104 بينما القاعدة على 149، وملف خدمة النسخ الدورية ops/sa.36t.backup.plist غير مثبَّت في
// ~/Library/LaunchAgents. أي أن «لا نسخة صالحة» حالةٌ واقعة، والبوابة كانت تمرّ عليها بأخضر.
//
// الثابت المحروس: فرعُ «لا نسخة احتياطية» لا يُصدر نجاحًا.
//
// ولماذا يُقرأ المصدر بدل تشغيل البوابة: تشغيلها كاملةً يرفع خوادم ويستغرق دقائق، و newestBackup() تمسح
// جذور المستودع الحقيقية فلا يمكن اصطناع «لا نسخة» في بيئة فيها نسخ فعلًا. فالمقروء هو الفرع نفسه.

const source = readFileSync(new URL('../scripts/gate.mjs', import.meta.url), 'utf8');

/** سطر فرع «لا نسخة احتياطية» في الفحص 5، بشكله لا بنصّه — فلا يتعلّق الاختبار بصياغة تتغيّر. */
const noBackupBranch = source.split('\n').find(line => /if\s*\(\s*!\s*backup\s*\)\s*return/.test(line));

test('البوابة تجد فرع «لا نسخة احتياطية» في فحص الاستعادة', () => {
  assert.ok(noBackupBranch,
    'لم يعد في scripts/gate.mjs فرعٌ يعالج غياب النسخة الاحتياطية — إمّا أُزيل الفحص أو غُيّر شكله، '
    + 'وفي الحالين يلزم إعادة النظر في هذا الحارس بدل حذفه.');
});

test('غياب النسخة الاحتياطية يوقف البوابة ولا يمرّ بها: skipped ليس نجاحًا', () => {
  assert.doesNotMatch(noBackupBranch, /ok:\s*true/,
    'فرع «لا نسخة احتياطية» يعيد ok:true، فالبوابة تُصدر أخضر على نظام لم تُجرَّب فيه استعادة قط. '
    + 'وهذا نقيض الغرض الذي بُنيت له البوابة: شبكةُ أمان تقول إنها موجودة وهي غائبة.\n'
    + `الفرع كما هو الآن: ${noBackupBranch.trim()}`);
});

test('ورسالة الفرع تقول للقارئ ما يفعله، لا أنه لم يُجرَّب شيء فحسب', () => {
  assert.match(noBackupBranch, /backup\.mjs/,
    'الرفض يسمّي الأداة التي تأخذ النسخة (scripts/backup.mjs) فيعرف القارئ خطوته التالية، '
    + 'على معيار الرفض في المنصة: ما الناقص، ومن يملكه، وما الخطوة.');
});
