/* ساعات مثبّتة لاختبارات حدّ اليوم بين الرياض وUTC.
 *
 * قيس العطب في 1 أكتوبر 2026 الساعة 02:05 بتوقيت الرياض (23:05 UTC من 30 سبتمبر): تاريخ الرياض أكتوبر وتاريخ UTC
 * سبتمبر، فكل مقارنة لتاريخ الرياض بطابع UTC تخطئ ثلاث ساعات كل يوم، وتخطئ في «الشهر» عند أول كل شهر.
 * الاختبار الذي يقرأ ساعة الجهاز يمرّ أو يسقط بحسب ساعة تشغيله؛ هذه الساعات تجعله يُشغَّل عمدًا على جانبَي الحد.
 *
 *   قبل الحد:    23:05 الرياض من آخر يوم في الشهر = 20:05 UTC — التقويمان على اليوم نفسه.
 *   داخل الفجوة: 02:05 الرياض من أول الشهر      = 23:05 UTC من اليوم السابق — الرياض أكتوبر وUTC سبتمبر.
 *   بعد الفجوة:  12:05 الرياض من أول الشهر      = 09:05 UTC — التقويمان على أكتوبر.
 *
 * التثبيت بساعات node:test الوهمية (Date وحده): Date.now() وnew Date() وIntl على new Date() كلها تقرأ الساعة المثبتة،
 * والمؤقتات والوعود تعمل كما هي. ساعة SQLite الداخلية ('now') لا تتأثر، ولا يقرؤها شيء في هذه الاختبارات.
 */
export const GAP_CLOCKS=Object.freeze([
  {label:'قبل الحد',at:'2026-09-30T20:05:00.000Z'},
  {label:'داخل الفجوة',at:'2026-09-30T23:05:00.000Z'},
  {label:'بعد الفجوة',at:'2026-10-01T09:05:00.000Z'}
]);

export function pinClock(t,at){
  t.mock.timers.enable({apis:['Date'],now:Date.parse(at)});
}

// يسجّل الاختبار نفسه مرة على كل ساعة من GAP_CLOCKS، باسمه مضافًا إليه الساعة.
export function onEveryClock(test,name,body){
  for(const clock of GAP_CLOCKS)test(`${name} [${clock.label} ${clock.at}]`,t=>{pinClock(t,clock.at);return body(t);});
}
