// المنصة كانت تكتب «العدد + المفرد» دائمًا، فتقرأ الشاشات «3 خدمة» و«1 إدارات» و«15 يوم» و«6 يوم عمل».
// القاعدة أربع صور لا صورة واحدة:
//   1        → مفرد بلا رقم: «خدمة واحدة»
//   2        → مثنى بلا رقم: «خدمتان»
//   3–10     → العدد + جمع القلة: «3 خدمات»
//   11 فأكثر → العدد + مفرد منصوب (تمييز): «15 خدمة»
//   0        → العدد + الجمع: «0 خدمات» (وللشاشة أن تكتب «لا خدمة» بنفسها)
// الكسر (نصف يوم) خارج التمييز: «1.5 يوم» بالمفرد بلا تنوين.
// وحدة نقية بلا DOM ولا تخزين: تُستورد في الواجهة وفي الاختبارات معًا.

// كل اسم أربع صور: [مفرد مع «واحد»، مثنى، جمع قلة، مفرد منصوب للتمييز].
export const NOUNS={
  service:['خدمة واحدة','خدمتان','خدمات','خدمة'],
  department:['إدارة واحدة','إدارتان','إدارات','إدارة'],
  section:['قسم واحد','قسمان','أقسام','قسمًا'],
  day:['يوم واحد','يومان','أيام','يومًا'],
  working_day:['يوم عمل واحد','يوما عمل','أيام عمل','يوم عمل'],
  request:['طلب واحد','طلبان','طلبات','طلبًا'],
  earlier_request:['طلب سابق واحد','طلبان سابقان','طلبات سابقة','طلبًا سابقًا'],
  person:['منسوب واحد','منسوبان','منسوبين','منسوبًا'],
  task:['مهمة واحدة','مهمتان','مهام','مهمة'],
  event:['حدث واحد','حدثان','أحداث','حدثًا'],
  policy:['سياسة واحدة','سياستان','سياسات','سياسة']
};

// العدد واسمه بالصورة الصحيحة. forms إما مفتاح في NOUNS أو المصفوفة الرباعية نفسها.
export function countNoun(value,forms){
  const shapes=Array.isArray(forms)?forms:NOUNS[forms];
  if(!shapes)return `${value}`;
  const [one,two,few,many]=shapes;
  const n=Number(value);
  if(!Number.isFinite(n))return `${value}`;
  // الكسر يأخذ المفرد بلا تنوين: «1.5 يوم» لا «1.5 يومًا» ولا «1.5 أيام».
  if(!Number.isInteger(n))return `${value} ${many.replace(/ًا/g,'')}`;
  const abs=Math.abs(n);
  if(abs===1)return one;
  if(abs===2)return two;
  if(abs===0||(abs>=3&&abs<=10))return `${n} ${few}`;
  return `${n} ${many}`;
}

