import { tokens } from './arabic-text.mjs';

const LEGAL_FORMS=new Set(['شركه','موسسه','ذ','م','ش','المحدوده','محدوده','co','company','llc','ltd','est','inc']);
export function clientNameKey(value){
  const all=tokens(value),core=all.filter(word=>!LEGAL_FORMS.has(word));
  return (core.length?core:all).join(' ');
}
