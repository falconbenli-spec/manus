-- ── ليه ───────────────────────────────────────────────────────────────────────────────
-- request_versions هي سجل «وش قدّم الموظف بالضبط». القاعدة تمنع تعديل صفوفها وحذفها بمشغّلَي
-- version_no_update وversion_no_delete، وهذا يكفي داخل المنصة. لكن ملف SQLite على القرص يُفتح بأي أداة،
-- والمشغّل نفسه يُسقَط بسطر واحد. فما كان في الصف شيء يثبت أنه ما تغيّر من يوم ما انحفظ.
-- الختم هو الجواب: بصمة تُعاد حسابها من الصف نفسه، فإذا ما طابقت اللي فيه عرفنا إنه تبدّل.
--
-- ── وش يغطي الختم ─────────────────────────────────────────────────────────────────────
-- الصف كامل: رقم الطلب، ورقم النسخة، ولحظة تقديمها، واللقطة بحرفها (JSON بمفاتيح مرتبة).
-- يحسبه app/workflow.mjs في versionDigest عند التقديم، ويعيد حسابه verifyRequestVersions عند التحقق.
-- النموذج rowDigest وverifyChain في app/definitions.mjs، والصيغة والدالة canonical من هناك نفسها لا نسخة ثانية.
--
-- ── ليه العمود يقبل NULL وليه ما عبّيناه للصفوف القديمة ───────────────────────────────
-- تقدر تختم الصفوف القديمة الحين — تقرأ كل صف وتحسب بصمته وتكتبها. بس هذي البصمة ما تثبت شي:
-- تثبت إن الصف ما تغيّر **من لحظة الترحيل**، لا من لحظة التقديم. صفٌّ تبدّل قبل اليوم يطلع بعدها «سليم»،
-- وهذا أسوأ من لا ختم: تحقُّقٌ يقول «سليمة» عن صف ما يقدر يفحصه يغشّ اللي يقرأه.
-- فالصفوف اللي قبل هذا الترحيل تبقى NULL، وverifyRequestVersions يقول عنها «ما نقدر نتأكد منها» —
-- لا «سليمة» ولا «تغيّرت». والصفوف اللي بعده تنولد مختومة من محرك الطلبات نفسه.
-- يعني: التعبئة هنا قرارٌ بعدم التعبئة، مكتوب سببه، لا سهوٌ يُستدرك لاحقًا.
--
-- ── وش يتغيّر في السلوك ───────────────────────────────────────────────────────────────
-- ولا شيء. عمود جديد يقبل الفراغ، ما يُقرأ في أي شرط ولا يدخل أي مفتاح ولا فهرس.
-- الجملة الوحيدة اللي كانت تكتب في الجدول بالترتيب (INSERT ... VALUES بأربع قيم) صارت تسمّي أعمدتها.
--
-- ALTER TABLE ADD COLUMN ما يمسّ الصفوف الموجودة ولا يشغّل version_no_update: يعدّل وصف الجدول بس.
-- وطول 64 صورة sha256 بالست عشري كما يكتبها hash في app/db.mjs.
ALTER TABLE request_versions ADD COLUMN digest TEXT CHECK(digest IS NULL OR length(digest)=64);
