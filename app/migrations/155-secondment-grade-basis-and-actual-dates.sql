-- ————— العيب الأول: قيمة مخمَّنة تُصرف باسم سندٍ لا يذكرها —————
--
-- تعميم الانتداب (30 سبتمبر 2026) يعدّل جدول بدل الانتداب وجدول درجات الإركاب في المادة 65، وصفّ
-- policy_article_supersedes يقول بالحرف إن «التعميم» يعلو على «م65». والتعميم يذكر ثلاث فئات فقط:
-- العاملون 700 داخل المملكة و900 خارجها، ومدراء الإدارات 900/1200، ونواب الرئيس 1000/1500.
--
-- وفيه فجوتان لم يحسمهما المالك:
--   (أ) التعميم لا يذكر الرئيس التنفيذي إطلاقًا — لا صفًّا ولا قيمة.
--   (ب) التعميم يقول «مدراء الإدارات» واللائحة (م65) تقول «مدراء العموم». هل هما فئة واحدة؟
--
-- الترحيل 112 بذر نسخة التعميم فأجاب عن الفجوتين من تلقاء نفسه:
--   * صفّ ceo في نسخة التعميم حمل 2100/2500 منقولتين من م65، بحجة «التعميم صامت عن هذه الدرجة
--     فتبقى على اللائحة». وقياسه أن السكوت إبقاءٌ — وهذا استنباط لا نصّ: م65 منسوخة بالتعميم بقرار
--     مدوَّن، فإما أن التعميم استبدل الجدول كله فلا بدل للرئيس التنفيذي حتى يُقرَّر، أو أنه استبدل
--     ما ذكره وحده فتبقى قيم م65 لما سكت عنه. أيّ الاثنين قرارُ المالك لا قرارُ الترحيل.
--   * وصفّ gm حمل 900/1200 (قيم «مدراء الإدارات» في التعميم) باسمٍ مدموج «مدراء الإدارات / مدراء
--     العموم»، فسوّى بين الاسمين بلا تأكيد. والفرق مال: إن لم يكونا فئة واحدة فمدير العموم يبقى على
--     600/900 من م65 — أي نصف ما يُصرف له اليوم زيادةً بمقدار 50%.
--
-- وقياسُه أن العيب لم يكن في البيانات وحدها: app/travel.mjs كان يحسب من الصفّين ويُقترح حركة راتب
-- بلا كلمة، ويطبع في سند القرار «الدرجة A — الرئيس التنفيذي (بدل الانتداب ودرجات التذاكر — التعميم)»
-- فوق مبلغٍ مصدره م65 المنسوخة. فالقارئ يقرأ سندًا يُنسب إلى التعميم قيمةً ليست فيه. قياسُ ذلك في
-- الفحص: انتداب درجة A خمسة أيام داخل المملكة تحت التعميم اعتُمد بـ10,500.00 ريال بلا رفض.
--
-- ما يتغيّر: الفجوة تُسجَّل بيانًا مرجعيًّا، وapp/travel.mjs يرفض قبل الحساب رفضًا مكتوبًا يسمّي
-- ما الناقص ومن يملكه (refuse في app/refusal.mjs). لا قيمة تُخمَّن، ولا حركة راتب تُقترح، ولا
-- قرار يُعتمد. ولا تُمسّ قيم الترحيل 112: صفوفه محمية بمحفّز، والفجوة تُقرأ فوقها لا مكانها.
--
-- والشاهد على (ب) في هذا المستودع نفسه: الهيكل المعتمد (26 أغسطس 2026) رئيسٌ تنفيذي ونائبان
-- وأربع عشرة «إدارة» يرأس كلًّا منها «مدير إدارة»، ولا يوجد فيه مسمّى «مدير عموم» إطلاقًا. وهذا
-- يرجّح أنهما فئة واحدة، ولا يُغني عن تأكيد المالك: الترجيح ليس قرارًا، والفرق مالٌ يُصرف لشخص.

