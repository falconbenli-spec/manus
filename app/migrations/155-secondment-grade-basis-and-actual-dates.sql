  version_code TEXT NOT NULL CHECK(version_code IN ('regulation_art65','circular')),
  grade TEXT NOT NULL CHECK(grade IN ('ceo','deputy','gm','employee')),
  grade_code TEXT NOT NULL REFERENCES job_grades(code),
  -- بنود الرفض المكتوب كما يطلبها refuse: ما الذي رُفض، وما الناقص، ولماذا، ومن يملكه، وما الخطوة التالية.
  what TEXT NOT NULL CHECK(length(trim(what))>=10),
  document TEXT NOT NULL CHECK(length(trim(document))>=5),
  why TEXT NOT NULL CHECK(length(trim(why))>=10),
  owner TEXT NOT NULL CHECK(length(trim(owner))>=3),
  owner_role TEXT NOT NULL CHECK(length(trim(owner_role))>=2),
  next_step TEXT NOT NULL CHECK(length(trim(next_step))>=10),
  -- السند المؤرَّخ: أي وثيقة بأي تاريخ أنشأت الفجوة. قيمة بلا سند لا تُكتب، وفجوة بلا سند لا تُسجَّل.
  source TEXT NOT NULL CHECK(length(trim(source))>=10),
  PRIMARY KEY(version_code,grade)
) STRICT;
-- الفجوة تُغلق بترحيل يحمل قرار المالك، لا بتحرير الصفّ: القرار حدثٌ له تاريخ.
CREATE TRIGGER secondment_grade_basis_gaps_fixed BEFORE UPDATE ON secondment_grade_basis_gaps
BEGIN SELECT RAISE(ABORT,'a basis gap is closed by a new migration carrying the decision, never edited'); END;
CREATE TRIGGER secondment_grade_basis_gaps_no_delete BEFORE DELETE ON secondment_grade_basis_gaps
BEGIN SELECT RAISE(ABORT,'basis gaps are retained'); END;

